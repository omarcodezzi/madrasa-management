#!/usr/bin/env bash
# First-time setup: writes deploy/.env with random secrets and a strong admin password.
# Run on the server from the deploy folder:  ./setup.sh
set -euo pipefail
cd "$(dirname "$0")"
if [[ -f .env ]]; then echo ".env already exists. Delete it first if you really want new secrets (the database keeps the old SA password!)."; exit 1; fi

read -r -p "Domain name for the site (e.g. madrasa.example.com): " DOMAIN
read -r -p "Email for Let's Encrypt certificate notices: " ACME_EMAIL
[[ -n "$DOMAIN" && -n "$ACME_EMAIL" ]] || { echo "Domain and email are both required."; exit 1; }

rand() { LC_ALL=C tr -dc "$1" < /dev/urandom | head -c "$2"; }
SA_PASSWORD="Sa$(rand 'A-Za-z0-9' 24)!9"
JWT_KEY="$(rand 'A-Za-z0-9' 64)"
ADMIN_PASSWORD="$(rand 'A-HJ-NP-Za-km-z2-9' 16)"

umask 077
cat > .env <<ENV
# Generated by setup.sh on $(date '+%F %T'). Keep this file secret and backed up somewhere safe.
DOMAIN=${DOMAIN}
ACME_EMAIL=${ACME_EMAIL}
SA_PASSWORD=${SA_PASSWORD}
JWT_KEY=${JWT_KEY}
ADMIN_USER=admin
# Used only once, to create the first admin. Change it after the first sign-in.
ADMIN_PASSWORD=${ADMIN_PASSWORD}
BACKUP_HOUR=2
RETAIN_DAYS=14
ENV
chmod +x backup.sh restore.sh

echo
echo "Saved deploy/.env"
echo "--------------------------------------------------------------"
echo " First sign-in:   https://${DOMAIN}"
echo " User name:       admin"
echo " Password:        ${ADMIN_PASSWORD}"
echo "--------------------------------------------------------------"
echo "Write the password down now, then change it from the profile menu after signing in."
echo "Next: point the domain's DNS A record to this server, then run:  docker compose up -d --build"
